  assert.equal(r.status, 200, JSON.stringify(r.body)); assert.equal(r.body.profile.heightCm, 180); assert.equal(r.body.weights.length, 2); assert.ok(r.body.estimate.prediction); assert.equal(r.body.estimate.proposedCalories, null);
  const unchanged = (await Targets.findOne({userId:users[0]._id})).calories;
