  r = await api('POST', '/apply-target', { expectedRevision: 1 }); assert.equal(r.status, 200, JSON.stringify(r.body));
  assert.equal(r.body.profile.revision, 2);
  let targets = await Targets.findOne({ userId: users[0]._id });
  assert.equal(targets.calories, r.body.appliedCalories); assert.equal(targets.waterMilliliters, 2000); assert.equal(targets.fiberGrams, 25);
  assert.equal(await Targets.countDocuments({ userId: users[1]._id }), 0);
  assert.equal((await api('POST', '/apply-target', { expectedRevision: 1 })).status, 409);
  r = await api('PUT', '', { ...input, weightKg: 79, expectedRevision: 2 }); assert.equal(r.status, 200);
  assert.equal(r.body.profile.weights.length, 1); assert.equal(r.body.profile.weights[0].weightKg, 79);
  assert.equal(r.body.profile.baseline.weightKg, 80);
  r = await api('PUT', '', { ...input, age: 17, expectedRevision: 3 }); assert.equal(r.status, 200);
  assert.equal((await api('POST', '/apply-target', { expectedRevision: 4 })).status, 400);
  const past = new Date(Date.parse(date + 'T00:00:00Z') - 86400000).toISOString().slice(0,10);
  const weightPath = '/weights/' + date;
  r = await api('PUT', weightPath, { weightKg: 70, units: 'metric', expectedRevision: 0 }, 3);
  assert.equal(r.status, 200, JSON.stringify(r.body)); assert.equal(r.body.profile, null); assert.equal(r.body.revision, 1); assert.equal(r.body.latestWeight.weightKg, 70);
  assert.equal((await api('GET', weightPath, null, 3)).body.entry.weightKg, 70);
  assert.equal((await api('PUT', weightPath, { weightKg: 69, units: 'metric', expectedRevision: 0 }, 3)).status, 409);
  assert.equal((await api('PUT', weightPath, { weightKg: '69', units: 'metric', expectedRevision: 1 }, 3)).status, 400);
  r = await api('PUT', '/weights/' + past, { weightKg: 71, units: 'metric', expectedRevision: 1 }, 3);
  assert.equal(r.status, 200); assert.equal(r.body.latestWeight.weightKg, 70); assert.equal(r.body.weights.length, 2);
  r = await api('PUT', weightPath, { weightKg: 69, units: 'metric', expectedRevision: 2 }, 3);
  assert.equal(r.status, 200); assert.equal(r.body.weights.length, 2); assert.equal(r.body.latestWeight.weightKg, 69);
  assert.equal((await api('POST', '/apply-target', {expectedRevision:3}, 3)).status, 400);
