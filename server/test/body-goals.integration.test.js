  let r = await api('PUT', '', input); assert.equal(r.status, 200, JSON.stringify(r.body));
  assert.equal(r.body.profile.revision, 1); assert.equal(r.body.profile.weights.length, 1);
  assert.equal((await api('GET')).body.profile.weightKg, 80);
  assert.equal((await api('GET', '', null, 1)).body.profile, null);
  assert.equal((await api('PUT', '', input)).status, 409);
  assert.equal((await api('POST', '/apply-target', { expectedRevision: 1 })).status, 409);
