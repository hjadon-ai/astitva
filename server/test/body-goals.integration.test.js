  const m = require('mongoose'); await m.connect(uri);
  t.after(async () => { await m.connection.dropDatabase(); await m.disconnect(); });
  const User = require('../src/models/User'), Session = require('../src/models/Session'), Flags = require('../src/models/InvitedEmail');
  const Body = require('../src/models/BodyGoals'), { Targets } = require('../src/models/Diet');
  await Promise.all([Body.init(), Targets.init()]);
